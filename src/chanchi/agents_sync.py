"""Compile harness-neutral agent sources into per-harness wrappers (docs/designs/chanchi-agents-mvp.md)."""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path

from chanchi.errors import ChanchiError

SCOPES = ("main", "subagent", "both")
PROFILES = ("read-only", "workspace-write", "orchestrator")
NAME = re.compile(r"^agent-chanchi-[a-z0-9]+(-[a-z0-9]+)*$")
WRAPPER_GLOBS = (".claude/agents/agent-chanchi-*.md", ".opencode/agents/agent-chanchi-*.md",
                 ".agents/agents/agent-chanchi-*/agent.md")

# agy tool names, read from the agy 1.5.14 agent definitions on 2026-11-21. Recheck after an agy upgrade
# (skill-chanchi-verify, Helpers).
AGY_READ_TOOLS = ("view_file", "list_dir", "find_by_name", "grep_search", "run_command", "command_status",
                  "send_command_input", "write_to_file", "search_web", "read_url_content")
AGY_EDIT_TOOLS = ("replace_file_content", "multi_replace_file_content")
AGY_ORCHESTRATOR_TOOLS = ("invoke_subagent", "define_subagent", "manage_task")

# Whether the harness preloads skills natively in this launch mode. Verified live in Task 8;
# where False, the generator writes an explicit "load these skills" line instead.
AGY_PRELOAD_VERIFIED = False


@dataclass(frozen=True)
class AgentSource:
    name: str
    description: str
    scope: str
    profile: str
    skills: list[str]
    body: str


def _parse(path: Path) -> AgentSource:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n") or "\n---\n" not in text[4:]:
        raise ChanchiError("invalid_value", f"{path}: missing frontmatter", field="frontmatter",
                           hint="start the file with a --- block holding name, description, scope, profile, skills")
    head, body = text[4:].split("\n---\n", 1)
    fields: dict[str, str] = {}
    for line in head.splitlines():
        if not line.strip():
            continue
        key, sep, value = line.partition(":")
        if not sep:
            raise ChanchiError("invalid_value", f"{path}: bad frontmatter line {line!r}", field="frontmatter",
                               hint="one `key: value` per line; no comments or nested blocks")
        fields[key.strip()] = value.strip()
    for key in ("name", "description", "scope", "profile"):
        if not fields.get(key):
            raise ChanchiError("invalid_value", f"{path}: {key} is required", field=key)
    if not NAME.match(fields["name"]) or fields["name"] != path.parent.name:
        raise ChanchiError("invalid_value", f"{path}: name must be agent-chanchi-<name> and equal the directory",
                           field="name")
    if fields["scope"] not in SCOPES:
        raise ChanchiError("invalid_value", f"{path}: unknown scope", field="scope", valid_values=SCOPES)
    if fields["profile"] not in PROFILES:
        raise ChanchiError("invalid_value", f"{path}: unknown profile", field="profile", valid_values=PROFILES)
    raw_skills = fields.get("skills", "[]")
    if not (raw_skills.startswith("[") and raw_skills.endswith("]")):
        raise ChanchiError("invalid_value", f"{path}: skills must be [a, b]", field="skills")
    skills = [s.strip() for s in raw_skills[1:-1].split(",") if s.strip()]
    return AgentSource(fields["name"], fields["description"], fields["scope"], fields["profile"], skills,
                       body.strip() + "\n")


def load_sources(agents_dir: Path) -> list[AgentSource]:
    if not agents_dir.is_dir():
        return []
    return [_parse(d / "AGENT.md") for d in sorted(agents_dir.iterdir()) if d.is_dir()]


def _header(source: AgentSource) -> str:
    return f"# generated by chanchi agents sync from agents/{source.name}/AGENT.md; do not edit"


def _skills_line(source: AgentSource) -> str:
    return f"Before starting, load these skills: {', '.join(source.skills)}." if source.skills else ""


def _yaml_list(key: str, values) -> list[str]:
    return [f"{key}:", *[f"  - {v}" for v in values]] if values else []


def _indent(text: str) -> str:
    return "\n".join(f"  {line}" if line else "" for line in text.rstrip("\n").splitlines())


def _doc(head: list[str], body: str) -> str:
    return "---\n" + "\n".join(head) + "\n---\n" + body


def _claude(s: AgentSource) -> str:
    head = [_header(s), f"name: {s.name}", f"description: {json.dumps(s.description)}"]
    if s.profile == "read-only":
        head.append("disallowedTools: Edit, NotebookEdit")
    if s.scope == "main":
        prompt = s.body + (f"\n{_skills_line(s)}\n" if s.skills else "")
        return _doc(head + ["initialPrompt: |", _indent(prompt)], "")
    return _doc(head + _yaml_list("skills", s.skills), "\n" + s.body)


def _opencode(s: AgentSource) -> str:
    mode = {"main": "primary", "subagent": "subagent", "both": "all"}[s.scope]
    head = [_header(s), f"description: {json.dumps(s.description)}", f"mode: {mode}"]
    if s.profile == "read-only":
        head += ["permission:", "  edit: deny", "  write: deny"]
    line = _skills_line(s)
    return _doc(head, "\n" + s.body + (f"\n{line}\n" if line else ""))


def _agy(s: AgentSource) -> str:
    tools = list(AGY_READ_TOOLS)
    if s.profile != "read-only":
        tools += AGY_EDIT_TOOLS
    if s.profile == "orchestrator":
        tools += AGY_ORCHESTRATOR_TOOLS
    head = [_header(s), f"name: {s.name}", f"description: {json.dumps(s.description)}",
            f"mainAgent: {'false' if s.scope == 'subagent' else 'true'}",
            f"subagent: {'false' if s.scope == 'main' else 'true'}", *_yaml_list("tools", tools)]
    line = ""
    if AGY_PRELOAD_VERIFIED:
        head += _yaml_list("preloadSkills", s.skills)
    else:
        line = _skills_line(s)
    return _doc(head, "\n" + s.body + (f"\n{line}\n" if line else ""))


def render(source: AgentSource) -> dict[str, str]:
    return {
        f".claude/agents/{source.name}.md": _claude(source),
        f".opencode/agents/{source.name}.md": _opencode(source),
        f".agents/agents/{source.name}/agent.md": _agy(source),
    }


def sync(root: Path, *, check: bool = False) -> dict:
    root = Path(root).resolve()
    sources = load_sources(root / "agents")
    wanted: dict[str, str] = {}
    for source in sources:
        wanted.update(render(source))
    present = {str(p.relative_to(root)) for pattern in WRAPPER_GLOBS for p in root.glob(pattern)}
    stale = sorted(rel for rel, text in wanted.items()
                   if not (root / rel).is_file() or (root / rel).read_text(encoding="utf-8") != text)
    orphans = sorted(present - set(wanted))
    unchanged = sorted(set(wanted) - set(stale))
    if check:
        if stale or orphans:
            raise ChanchiError("stale_wrappers", f"generated agent wrappers are out of date: {stale + orphans}",
                               field="path", hint="run `chanchi agents sync` and commit the result; never edit "
                               "wrappers by hand, edit agents/<name>/AGENT.md", details={"stale": stale + orphans})
        return {"root": str(root), "agents": [s.name for s in sources], "written": [], "removed": [],
                "unchanged": unchanged}
    for rel in stale:
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(wanted[rel], encoding="utf-8")
    for rel in orphans:
        (root / rel).unlink()
        if rel.startswith(".agents/agents/") and not any((root / rel).parent.iterdir()):
            (root / rel).parent.rmdir()
    return {"root": str(root), "agents": [s.name for s in sources], "written": stale, "removed": orphans,
            "unchanged": unchanged}
