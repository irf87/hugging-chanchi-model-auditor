"""Compile harness-neutral agent sources into per-harness wrappers (docs/designs/chanchi-agents-mvp.md)."""

from __future__ import annotations

import hashlib
import json
import os
import re
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path

from chanchi import db, harnesses, projects, taxonomy
from chanchi.errors import ChanchiError

SCOPES = ("main", "subagent", "both")
PROFILES = harnesses.PROFILES
INSTALLS = ("repo", "user")
NAME = re.compile(r"^agent-chanchi-[a-z0-9]+(-[a-z0-9]+)*$")
WRAPPER_GLOBS = (
    ".claude/agents/agent-chanchi-*.md",
    ".opencode/agents/agent-chanchi-*.md",
    ".agents/agents/agent-chanchi-*/agent.md",
    ".cursor/agents/agent-chanchi-*.md",
)
USER_HEADER = "# generated by chanchi agents link --user from agents/{name}/AGENT.md; do not edit"
MIRROR_HEADER = "# generated by chanchi items mirror from SYNC/ITEMS/agents/{name}/AGENT.md; do not edit"
REPO_TARGETS = {
    "claude": lambda name: f".claude/agents/{name}.md",
    "opencode": lambda name: f".opencode/agents/{name}.md",
    "agy": lambda name: f".agents/agents/{name}/agent.md",
    "cursor": lambda name: f".cursor/agents/{name}.md",
}
MANIFEST_NAME = "mirror.json"
MANIFEST_OWNER = "agents-link"

# agy tool names, read from the agy 1.5.14 agent definitions on 2026-11-21. Recheck after an agy upgrade
# (skill-chanchi-verify, Helpers).
AGY_READ_TOOLS = ("view_file", "list_dir", "find_by_name", "grep_search", "run_command", "command_status",
                  "send_command_input", "write_to_file", "search_web", "read_url_content")
AGY_EDIT_TOOLS = ("replace_file_content", "multi_replace_file_content")
AGY_ORCHESTRATOR_TOOLS = ("invoke_subagent", "define_subagent", "manage_task")

# agy preloads skills listed under `preloadSkills:` (not `skills:`), verified live on agy 1.5.14
# (phase-1 session S5, 2026-11-21). Set to False to fall back to an explicit "load these skills" line.
AGY_PRELOAD_VERIFIED = True


@dataclass(frozen=True)
class AgentSource:
    name: str
    description: str
    scope: str
    profile: str
    skills: list[str]
    body: str
    install: str = "repo"
    version: str | None = None
    status: str | None = None


def unquote(value: str) -> str:
    """Strip one pair of matching surrounding quotes."""
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def _parse(path: Path) -> AgentSource:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n") or "\n---\n" not in text[4:]:
        raise ChanchiError("invalid_value", f"{path}: missing frontmatter", field="frontmatter",
                           hint="start the file with a --- block holding name, description, scope, profile, skills")
    head, body = text[4:].split("\n---\n", 1)
    fields: dict[str, str] = {}
    for line in head.splitlines():
        if not line.strip():
            continue
        key, sep, value = line.partition(":")
        if not sep:
            raise ChanchiError("invalid_value", f"{path}: bad frontmatter line {line!r}", field="frontmatter",
                               hint="one `key: value` per line; no comments or nested blocks")
        fields[key.strip()] = value.strip()
    for key in ("name", "description", "scope", "profile"):
        if not fields.get(key):
            raise ChanchiError("invalid_value", f"{path}: {key} is required", field=key)
    if not NAME.match(fields["name"]) or fields["name"] != path.parent.name:
        raise ChanchiError("invalid_value", f"{path}: name must be agent-chanchi-<name> and equal the directory",
                           field="name")
    if fields["scope"] not in SCOPES:
        raise ChanchiError("invalid_value", f"{path}: unknown scope", field="scope", valid_values=SCOPES)
    if fields["profile"] not in PROFILES:
        raise ChanchiError("invalid_value", f"{path}: unknown profile", field="profile", valid_values=PROFILES)
    install = fields.get("install", "repo")
    if install not in INSTALLS:
        raise ChanchiError("invalid_value", f"{path}: unknown install", field="install", valid_values=INSTALLS)
    version = status = None
    if "version" in fields:
        version = unquote(fields["version"])
        if not taxonomy.ITEM_VERSION.match(version):
            raise ChanchiError("invalid_value", f"{path}: version must be <major>.<minor>.<patch>", field="version")
    if "status" in fields:
        status = unquote(fields["status"])
        if status not in taxonomy.ITEM_STATUSES:
            raise ChanchiError("invalid_value", f"{path}: unknown status", field="status",
                               valid_values=taxonomy.ITEM_STATUSES)
    raw_skills = fields.get("skills", "[]")
    if not (raw_skills.startswith("[") and raw_skills.endswith("]")):
        raise ChanchiError("invalid_value", f"{path}: skills must be [a, b]", field="skills")
    skills = [s.strip() for s in raw_skills[1:-1].split(",") if s.strip()]
    return AgentSource(fields["name"], fields["description"], fields["scope"], fields["profile"], skills,
                       body.strip() + "\n", install=install, version=version, status=status)


def load_sources(agents_dir: Path) -> list[AgentSource]:
    if not agents_dir.is_dir():
        return []
    return [_parse(d / "AGENT.md") for d in sorted(agents_dir.iterdir()) if d.is_dir()]


def _header(source: AgentSource) -> str:
    return f"# generated by chanchi agents sync from agents/{source.name}/AGENT.md; do not edit"


def _skills_line(source: AgentSource) -> str:
    return f"Before starting, load these skills: {', '.join(source.skills)}." if source.skills else ""


def _yaml_list(key: str, values) -> list[str]:
    return [f"{key}:", *[f"  - {v}" for v in values]] if values else []


def _indent(text: str) -> str:
    return "\n".join(f"  {line}" if line else "" for line in text.rstrip("\n").splitlines())


def _doc(head: list[str], body: str) -> str:
    return "---\n" + "\n".join(head) + "\n---\n" + body


def _claude(s: AgentSource, header: str) -> str:
    head = [header, f"name: {s.name}", f"description: {json.dumps(s.description)}"]
    if s.profile == "read-only":
        head.append("disallowedTools: Edit, NotebookEdit")
    if s.scope == "main":
        prompt = s.body + (f"\n{_skills_line(s)}\n" if s.skills else "")
        return _doc(head + ["initialPrompt: |", _indent(prompt)], "")
    return _doc(head + _yaml_list("skills", s.skills), "\n" + s.body)


def _opencode(s: AgentSource, header: str) -> str:
    mode = {"main": "primary", "subagent": "subagent", "both": "all"}[s.scope]
    head = [header, f"description: {json.dumps(s.description)}", f"mode: {mode}"]
    if s.profile == "read-only":
        head += ["permission:", "  edit: deny", "  write: deny"]
    line = _skills_line(s)
    return _doc(head, "\n" + s.body + (f"\n{line}\n" if line else ""))


def _agy(s: AgentSource, header: str) -> str:
    tools = list(AGY_READ_TOOLS)
    if s.profile != "read-only":
        tools += AGY_EDIT_TOOLS
    if s.profile == "orchestrator":
        tools += AGY_ORCHESTRATOR_TOOLS
    head = [header, f"name: {s.name}", f"description: {json.dumps(s.description)}",
            f"mainAgent: {'false' if s.scope == 'subagent' else 'true'}",
            f"subagent: {'false' if s.scope == 'main' else 'true'}", *_yaml_list("tools", tools)]
    line = ""
    if AGY_PRELOAD_VERIFIED:
        head += _yaml_list("preloadSkills", s.skills)
    else:
        line = _skills_line(s)
    return _doc(head, "\n" + s.body + (f"\n{line}\n" if line else ""))


def _cursor(s: AgentSource, header: str) -> str:
    head = [header, f"name: {s.name}", f"description: {json.dumps(s.description)}"]
    if s.profile == "read-only":
        head.append("readonly: true")
    line = _skills_line(s)
    return _doc(head, "\n" + s.body + (f"\n{line}\n" if line else ""))


def render_by_kind(source: AgentSource, header: str) -> dict[str, str]:
    """Compile an agent source into wrapper text keyed by harness kind."""
    return {
        "claude": _claude(source, header),
        "opencode": _opencode(source, header),
        "agy": _agy(source, header),
        "cursor": _cursor(source, header),
    }


def render(source: AgentSource) -> dict[str, str]:
    """Compile an agent source into repository wrapper paths."""
    return {REPO_TARGETS[kind](source.name): text for kind, text in render_by_kind(source, _header(source)).items()}


def sync(root: Path, *, check: bool = False) -> dict:
    root = Path(root).resolve()
    sources = load_sources(root / "agents")
    wanted: dict[str, str] = {}
    for source in sources:
        wanted.update(render(source))
    present = {str(p.relative_to(root)) for pattern in WRAPPER_GLOBS for p in root.glob(pattern)}
    stale = sorted(rel for rel, text in wanted.items()
                   if not (root / rel).is_file() or (root / rel).read_text(encoding="utf-8") != text)
    orphans = sorted(present - set(wanted))
    unchanged = sorted(set(wanted) - set(stale))
    if check:
        if stale or orphans:
            raise ChanchiError("stale_wrappers", f"generated agent wrappers are out of date: {stale + orphans}",
                               field="path", hint="run `chanchi agents sync` and commit the result; never edit "
                               "wrappers by hand, edit agents/<name>/AGENT.md", details={"stale": stale + orphans})
        return {"root": str(root), "agents": [s.name for s in sources], "written": [], "removed": [],
                "unchanged": unchanged}
    for rel in stale:
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(wanted[rel], encoding="utf-8")
    for rel in orphans:
        (root / rel).unlink()
        if rel.startswith(".agents/agents/") and not any((root / rel).parent.iterdir()):
            (root / rel).parent.rmdir()
    return {"root": str(root), "agents": [s.name for s in sources], "written": stale, "removed": orphans,
            "unchanged": unchanged}


def repo_root() -> Path:
    """The chanchi repository root containing this module."""
    return Path(__file__).resolve().parents[2]


def _normalize_root(root: Path) -> str:
    resolved = Path(root).expanduser().resolve()
    main = projects.main_worktree(resolved)
    return str(main if main is not None else resolved)


def norm_path(path: Path | str) -> str:
    p = Path(path)
    return str(p.parent.resolve() / p.name)


def sha256_bytes(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


# --- user-level agent files: composable primitives shared by `agents link --user` and `items mirror` ---


def read_manifest(manifest_path: Path) -> list[dict]:
    if not manifest_path.exists():
        return []
    try:
        data = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError, OSError) as exc:
        raise ChanchiError("invalid_value", f"{manifest_path}: invalid manifest ({exc})", field="manifest",
                           hint="fix or remove mirror.json") from None
    if not isinstance(data, dict) or data.get("version") != 1 or not isinstance(data.get("entries"), list):
        raise ChanchiError("invalid_value", f"{manifest_path}: manifest must have version 1 and entries list",
                           field="manifest", hint="fix or remove mirror.json")
    if any(not isinstance(entry, dict) or not isinstance(entry.get("path"), str) for entry in data["entries"]):
        raise ChanchiError("invalid_value", f"{manifest_path}: every manifest entry needs a string path",
                           field="manifest", hint="fix or remove mirror.json")
    return list(data["entries"])


def write_manifest(manifest_path: Path, entries: list[dict]) -> None:
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(json.dumps({"version": 1, "entries": entries}, indent=2) + "\n", encoding="utf-8")


def remove_target(path: Path, *, is_agy: bool) -> bool:
    removed = False
    if path.is_file() or path.is_symlink():
        path.unlink()
        removed = True
    if (is_agy or path.name == "agent.md") and path.parent.is_dir() and not any(path.parent.iterdir()):
        path.parent.rmdir()
    return removed


def plan_agents(
    sources: list[AgentSource],
    header: str,
    *,
    harness_keys: list[str],
    env: Mapping[str, str] | None,
    home: Path,
) -> dict[str, tuple[str, str, str]]:
    """The wanted user-level agent files: normalized path -> (harness kind, text, sha256), for each source
    and each harness in `harness_keys`. `header` is a format string with `{name}`."""
    wanted: dict[str, tuple[str, str, str]] = {}
    for source in sources:
        rendered = render_by_kind(source, header.format(name=source.name))
        for kind in harness_keys:
            target = norm_path(harnesses.user_agent_path(kind, source.name, env=env, home=home))
            wanted[target] = (kind, rendered[kind], sha256_bytes(rendered[kind].encode("utf-8")))
    return wanted


def entry_conflicts(paths: Iterable[str], owned_by_path: Mapping[str, dict], all_by_path: Mapping[str, dict]) -> list[str]:
    """Wanted paths this owner may not write: owned by another manifest entry, existing but unowned, or a
    real directory."""
    conflicts: list[str] = []
    for path_str in sorted(paths):
        target = Path(path_str)
        if path_str in all_by_path and path_str not in owned_by_path:
            conflicts.append(path_str)
        elif path_str not in owned_by_path and os.path.lexists(path_str):
            conflicts.append(path_str)
        elif target.is_dir() and not target.is_symlink():
            conflicts.append(path_str)
    return conflicts


def agent_issues(wanted: dict[str, tuple[str, str, str]], owned_by_path: Mapping[str, dict], orphans: list[str],
                 conflicts: list[str]) -> list[str]:
    """Paths whose file is missing, changed, unrecorded, orphaned or in conflict."""
    stale: list[str] = []
    for path_str, (_kind, _text, digest) in sorted(wanted.items()):
        if path_str in conflicts:
            continue
        entry = owned_by_path.get(path_str)
        target = Path(path_str)
        if entry is None or not target.is_file() or target.is_symlink():
            stale.append(path_str)
            continue
        disk_digest = sha256_bytes(target.read_bytes())
        if disk_digest != digest or disk_digest != entry.get("sha256"):
            stale.append(path_str)
    return sorted(set(stale + orphans + conflicts))


def write_agents(wanted: dict[str, tuple[str, str, str]]) -> tuple[list[str], list[str]]:
    """Write every wanted file whose bytes differ; returns (written, unchanged), each sorted."""
    written: list[str] = []
    unchanged: list[str] = []
    for path_str, (_kind, text, digest) in sorted(wanted.items()):
        target = Path(path_str)
        if target.is_file() and not target.is_symlink() and sha256_bytes(target.read_bytes()) == digest:
            unchanged.append(path_str)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(text.encode("utf-8"))
            written.append(path_str)
    return written, unchanged


def link_user(
    root: Path,
    *,
    env: Mapping[str, str] | None = None,
    home: Path | None = None,
    db_dir: Path | None = None,
    check: bool = False,
    remove: bool = False,
) -> dict:
    """Compile `install: user` agent sources into installed user harness folders with manifest ownership."""
    if check and remove:
        raise ChanchiError("invalid_value", "--check and --remove are mutually exclusive", field="check",
                           hint="pass either --check or --remove, not both")
    resolved_env = os.environ if env is None else env
    resolved_home = (Path.home() if home is None else Path(home)).expanduser().resolve()
    resolved_db_dir = db.operational_path().parent if db_dir is None else Path(db_dir)
    manifest_path = resolved_db_dir / MANIFEST_NAME
    entries = read_manifest(manifest_path)

    norm_root = _normalize_root(root)
    active_harnesses = [k for k in harnesses.KEYS if harnesses.installed(k, env=resolved_env, home=resolved_home)]
    skipped_harnesses = [k for k in harnesses.KEYS if k not in active_harnesses]

    owned = [e for e in entries if e.get("owner") == MANIFEST_OWNER and e.get("root") == norm_root]
    other = [e for e in entries if not (e.get("owner") == MANIFEST_OWNER and e.get("root") == norm_root)]
    owned_by_path = {norm_path(e["path"]): e for e in owned}
    all_by_path = {norm_path(e["path"]): e for e in entries}

    if remove:
        removed = sorted(
            e["path"] for e in owned if remove_target(Path(e["path"]), is_agy=e.get("kind") == "agy")
        )
        if manifest_path.exists() and owned:
            write_manifest(manifest_path, other)
        return {
            "root": norm_root,
            "written": [],
            "unchanged": [],
            "removed": removed,
            "conflicts": [],
            "skipped_harnesses": skipped_harnesses,
        }

    sources = [s for s in load_sources(Path(root).expanduser().resolve() / "agents") if s.install == "user"]
    wanted = plan_agents(sources, USER_HEADER, harness_keys=active_harnesses, env=resolved_env, home=resolved_home)
    conflicts = entry_conflicts(wanted, owned_by_path, all_by_path)
    orphans = sorted(p for p in owned_by_path if p not in wanted)

    if check:
        issues = agent_issues(wanted, owned_by_path, orphans, conflicts)
        if issues:
            raise ChanchiError(
                "stale_wrappers",
                f"user agent wrappers are out of date: {issues}",
                field="path",
                hint="run `chanchi agents link --user` to update user-level agent wrappers",
                details={"stale": issues, "conflicts": conflicts},
            )
        return {
            "root": norm_root,
            "agents": [s.name for s in sources],
            "written": [],
            "unchanged": sorted(wanted),
            "removed": [],
            "conflicts": [],
            "skipped_harnesses": skipped_harnesses,
        }

    if conflicts:
        raise ChanchiError(
            "link_conflict",
            f"user agent paths conflict with existing or foreign-owned entries: {conflicts}",
            field="path",
            hint="remove the conflicting files or resolve the other owner before running `chanchi agents link --user`",
            details={"conflicts": conflicts},
        )

    written, unchanged = write_agents(wanted)
    removed = sorted(p for p in orphans if remove_target(Path(p), is_agy=owned_by_path[p].get("kind") == "agy"))
    new_owned = [
        {"owner": MANIFEST_OWNER, "root": norm_root, "path": path_str, "kind": kind, "sha256": digest}
        for path_str, (kind, _text, digest) in sorted(wanted.items())
    ]
    write_manifest(manifest_path, other + new_owned)
    return {
        "root": norm_root,
        "agents": [s.name for s in sources],
        "written": written,
        "unchanged": unchanged,
        "removed": removed,
        "conflicts": [],
        "skipped_harnesses": skipped_harnesses,
    }
