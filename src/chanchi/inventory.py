"""Project item inventory: the item folders of registered projects, scanned read-only.

Design: docs/designs/global-items.md, "B. Capture" and "Data model (migration 006)". This module is a
domain module: it may import `db`, `items`, `projects`, `sync`, `taxonomy`, `errors` and `timeutil`;
`items` never imports it (the CLI passes scanned names into `items.check` and `items.mirror`). It opens
project files only for reading, never follows a symbolic link and never renders output.

An item is stored by its path relative to the project root, in POSIX form. A directory item (skill, or an
agent kept in `AGENT.md` or agy's `agent.md`) is stored as the directory; a single-file agent
(`.claude/agents/<name>.md`, `.opencode/agents/<name>.md`) as the file.
"""

from __future__ import annotations

import hashlib
import os
import posixpath
import re
import sqlite3
import stat
from collections.abc import Iterator
from contextlib import contextmanager
from pathlib import Path

from chanchi import db, items, projects
from chanchi.errors import ChanchiError
from chanchi.timeutil import utc_now

DEFAULT_ROOTS = (
    ".agents/skills",
    ".claude/skills",
    ".opencode/skills",
    "agents",
    ".claude/agents",
    ".opencode/agents",
    ".agents/agents",
)
AGENT_FILE_ROOTS = (".claude/agents", ".opencode/agents")
AGY_AGENTS_ROOT = ".agents/agents"
MAX_DEPTH = 4
SKIPPED_NAMES = ("node_modules",)
GENERATED_PREFIX = "# generated by chanchi"
BLOCK_MARKER = re.compile(r"^[>|][+-]?\d*$")
_FIELDS = ("kind", "name", "sha256", "lines", "description")


@contextmanager
def _write(conn: sqlite3.Connection) -> Iterator[sqlite3.Connection]:
    """One write transaction; joins the caller's transaction when one is already open."""
    if conn.in_transaction:
        yield conn
    else:
        with db.transaction(conn):
            yield conn


# --- project root and item dirs -----------------------------------------------------------


def project_root(conn: sqlite3.Connection, project_id: int) -> Path | None:
    """The first path locator of the project (lowest id) that is an existing directory, else None."""
    for row in conn.execute(
        "SELECT value FROM project_locators WHERE project_id = ? AND kind = 'path' ORDER BY id",
        (project_id,),
    ):
        candidate = Path(row["value"])
        if candidate.is_dir():
            return candidate
    return None


def require_root(conn: sqlite3.Connection, project_id: int, slug: str) -> Path:
    root = project_root(conn, project_id)
    if root is None:
        raise ChanchiError(
            "missing_prerequisite",
            f"project {slug!r} has no existing folder on this machine",
            field="project",
            hint=f"cd into the project and run `chanchi project relink {slug}`",
        )
    return root


def _bad_path(message: str, *, hint: str | None = None) -> ChanchiError:
    return ChanchiError("invalid_value", message, field="path", hint=hint)


def _normalize(path: str) -> str:
    """A relative POSIX path without empty or `.` components; refuses anything that could leave the root."""
    if not isinstance(path, str) or not path.strip():
        raise _bad_path("path must not be empty", hint="pass a folder relative to the project root")
    if "\0" in path:
        raise _bad_path("path must not contain a NUL character")
    if path.startswith("/"):
        raise _bad_path(f"{path!r} is absolute", hint="pass a path relative to the project root")
    parts = [part for part in path.split("/") if part not in ("", ".")]
    if ".." in parts:
        raise _bad_path(f"{path!r} contains '..'", hint="pass a path inside the project root")
    if not parts:
        raise _bad_path(f"{path!r} is the project root itself", hint="pass a folder below the project root")
    return "/".join(parts)


def _root_state(root: Path, rel: str) -> str:
    """`ok` when every component from the project root down to `rel` is a real directory,
    `symlink` when one is a link (never entered), `absent` when one is missing or not a directory."""
    current = root
    for part in rel.split("/"):
        current = current / part
        try:
            mode = os.lstat(current).st_mode
        except OSError:
            return "absent"
        if stat.S_ISLNK(mode):
            return "symlink"
        if not stat.S_ISDIR(mode):
            return "absent"
    return "ok"


def item_dirs(conn: sqlite3.Connection, project_id: int) -> list[str]:
    """The agnostic folders the project registered with `project items-dirs --add`, sorted."""
    rows = conn.execute("SELECT path FROM project_item_dirs WHERE project_id = ? ORDER BY path", (project_id,))
    return [row["path"] for row in rows]


def add_item_dir(conn: sqlite3.Connection, project_id: int, root: Path, path: str) -> dict:
    """Register an extra scan root: an existing real directory below `root`, not a default root."""
    norm = _normalize(path)
    if norm in DEFAULT_ROOTS:
        raise _bad_path(f"{norm} is already scanned by default", hint="pass another folder")
    state = _root_state(Path(root), norm)
    if state == "symlink":
        raise _bad_path(f"{norm} is or sits under a symbolic link; scans never follow links")
    if state == "absent":
        raise _bad_path(f"{norm} is not an existing directory under the project root")
    with _write(conn):
        stored = conn.execute(
            "SELECT 1 FROM project_item_dirs WHERE project_id = ? AND path = ?", (project_id, norm)
        ).fetchone()
        if stored is not None:
            return {"path": norm, "added": False}
        conn.execute("INSERT INTO project_item_dirs (project_id, path) VALUES (?, ?)", (project_id, norm))
    return {"path": norm, "added": True}


def remove_item_dir(conn: sqlite3.Connection, project_id: int, path: str) -> dict:
    """Delete a registered scan root; a path that is not registered is refused."""
    norm = _normalize(path)
    with _write(conn):
        cursor = conn.execute("DELETE FROM project_item_dirs WHERE project_id = ? AND path = ?", (project_id, norm))
        if cursor.rowcount == 0:
            raise _bad_path(
                f"{norm} is not a registered item folder",
                hint="run `chanchi project items-dirs` to list them",
            )
    return {"path": norm, "removed": True}


# --- frontmatter ----------------------------------------------------------------------------


def _block(text: str) -> list[str] | None:
    """The lines between a first-line `---` fence and the next `---` line, or None."""
    lines = text.lstrip("﻿").split("\n")
    if not lines or lines[0].rstrip() != "---":
        return None
    for index in range(1, len(lines)):
        if lines[index].rstrip() == "---":
            return [line.rstrip("\r") for line in lines[1:index]]
    return None


def _unquote(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def frontmatter(text: str) -> dict:
    """A lenient reader for `name` and `description`; it never raises.

    Comment lines are ignored; a description that is empty or a `>`, `>-`, `|` or `|-` marker takes the
    more-indented lines that follow, joined with single spaces. The strict `items.read_frontmatter`
    refuses folded values, comments and nested maps that project files use.
    """
    found: dict[str, str | None] = {"name": None, "description": None}
    block = _block(text)
    if block is None:
        return found
    seen: set[str] = set()
    index = 0
    while index < len(block):
        line = block[index]
        index += 1
        if not line.strip() or line[0] in " \t" or line.startswith("#"):
            continue
        key, sep, value = line.partition(":")
        key, value = key.strip(), value.strip()
        if not sep or key not in found or key in seen:
            continue
        seen.add(key)
        if not value or BLOCK_MARKER.match(value):
            parts = []
            while index < len(block) and (block[index][:1] in (" ", "\t") or not block[index].strip()):
                if block[index].strip():
                    parts.append(block[index].strip())
                index += 1
            value = " ".join(parts)
        else:
            value = _unquote(value).strip()
        found[key] = value or None
    return found


def description(text: str) -> str | None:
    return frontmatter(text)["description"]


def _generated(text: str) -> bool:
    block = _block(text)
    return block is not None and any(line.startswith(GENERATED_PREFIX) for line in block)


# --- walk -----------------------------------------------------------------------------------


class _Walk:
    def __init__(self, root: Path) -> None:
        self.root = root
        self.found: dict[str, dict] = {}
        self.skipped: set[tuple[str, str]] = set()

    def skip(self, path: str, reason: str) -> None:
        self.skipped.add((path, reason))

    def directory(self, rel: str, depth: int) -> None:
        folder = self.root / rel
        try:
            with os.scandir(folder) as scanned:
                entries = sorted(scanned, key=lambda e: e.name)
        except OSError:
            self.skip(rel, "unreadable")
            return
        main = self._main_file(entries, rel)
        if main is not None:
            self.item(rel, *main)
            return
        for entry in entries:
            name = entry.name
            if name.startswith(".") or name in SKIPPED_NAMES:
                continue
            child = f"{rel}/{name}"
            if entry.is_symlink():
                self.skip(child, "symlink")
            elif entry.is_dir(follow_symlinks=False):
                if depth < MAX_DEPTH:
                    self.directory(child, depth + 1)
            elif rel in AGENT_FILE_ROOTS and name.endswith(".md") and entry.is_file(follow_symlinks=False):
                self.single_file(child, name)

    @staticmethod
    def _main_file(entries: list[os.DirEntry], rel: str) -> tuple[str, str, bool] | None:
        """(kind, main file name, main file is a link) when the directory is an item."""
        by_name = {entry.name: entry for entry in entries}
        wanted = [("skill", "SKILL.md"), ("agent", "AGENT.md")]
        if posixpath.dirname(rel) == AGY_AGENTS_ROOT:
            wanted.append(("agent", "agent.md"))
        for kind, name in wanted:
            entry = by_name.get(name)
            if entry is None:
                continue
            if entry.is_symlink():
                return kind, name, True
            if entry.is_file(follow_symlinks=False):
                return kind, name, False
        return None

    def item(self, rel: str, kind: str, main_name: str, linked: bool) -> None:
        if linked:
            self.skip(rel, "symlink")
            return
        folder = self.root / rel
        try:
            text = (folder / main_name).read_bytes().decode("utf-8")
        except (OSError, UnicodeDecodeError):
            self.skip(rel, "unreadable")
            return
        if _generated(text):
            self.skip(rel, "generated")
            return
        try:
            digest = items.content_hash(folder)
        except ChanchiError:
            self.skip(rel, "symlink")
            return
        except OSError:
            self.skip(rel, "unreadable")
            return
        meta = frontmatter(text)
        self.found[rel] = {
            "kind": kind,
            "name": meta["name"] or folder.name,
            "path": rel,
            "sha256": digest,
            "lines": len(text.splitlines()),
            "description": meta["description"],
        }

    def single_file(self, rel: str, file_name: str) -> None:
        try:
            data = (self.root / rel).read_bytes()
            text = data.decode("utf-8")
        except (OSError, UnicodeDecodeError):
            self.skip(rel, "unreadable")
            return
        if _generated(text):
            self.skip(rel, "generated")
            return
        meta = frontmatter(text)
        self.found[rel] = {
            "kind": "agent",
            "name": meta["name"] or file_name[: -len(".md")],
            "path": rel,
            "sha256": hashlib.sha256(data).hexdigest(),
            "lines": len(text.splitlines()),
            "description": meta["description"],
        }


def walk(root: Path, rel_roots: list[str]) -> tuple[list[dict], list[dict]]:
    """Items `{kind, name, path, sha256, lines, description}` and skipped `{path, reason}` below `root`.

    Each root in `rel_roots` is walked only when it and every component above it are real directories
    (checked with `lstat`); a linked one is listed as skipped and never entered. Reads files, never
    writes and never follows a link.
    """
    state = _Walk(Path(root))
    for rel in rel_roots:
        status = _root_state(state.root, rel)
        if status == "symlink":
            state.skip(rel, "symlink")
        elif status == "ok":
            state.directory(rel, 0)
    found = [state.found[path] for path in sorted(state.found)]
    skipped = [{"path": path, "reason": reason} for path, reason in sorted(state.skipped)]
    return found, skipped


# --- scan -----------------------------------------------------------------------------------


def _store(conn: sqlite3.Connection, project_id: int, found: list[dict], stamp: str) -> tuple[int, int, int]:
    """Insert new paths, update changed rows, delete vanished ones; stamp every row seen."""
    existing = {
        row["path"]: row
        for row in conn.execute("SELECT * FROM project_items WHERE project_id = ?", (project_id,))
    }
    added = changed = 0
    for item in found:
        row = existing.pop(item["path"], None)
        if row is None:
            conn.execute(
                "INSERT INTO project_items (project_id, kind, name, path, sha256, lines, description, scanned_at) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                (project_id, item["kind"], item["name"], item["path"], item["sha256"], item["lines"],
                 item["description"], stamp),
            )
            added += 1
        elif all(row[field] == item[field] for field in _FIELDS):
            conn.execute("UPDATE project_items SET scanned_at = ? WHERE id = ?", (stamp, row["id"]))
        else:
            conn.execute(
                "UPDATE project_items SET kind = ?, name = ?, sha256 = ?, lines = ?, description = ?, "
                "scanned_at = ? WHERE id = ?",
                (item["kind"], item["name"], item["sha256"], item["lines"], item["description"], stamp, row["id"]),
            )
            changed += 1
    for row in existing.values():
        conn.execute("DELETE FROM project_items WHERE id = ?", (row["id"],))
    return added, changed, len(existing)


def scan(conn: sqlite3.Connection, *, project: str | None = None, now: str | None = None) -> dict:
    """Fingerprint the items of every registered project (or one) into `project_items`.

    A project whose root is missing is listed under `missing` and keeps its stored rows. Each project is
    written in one transaction; a second scan of unchanged projects adds, changes and removes nothing.
    """
    stamp = now or utc_now()
    if project is not None:
        described = projects.show(conn, project)
        targets = [(described["id"], described["slug"])]
    else:
        targets = [
            (row["id"], row["slug"])
            for row in conn.execute("SELECT id, slug FROM projects WHERE registered_at IS NOT NULL ORDER BY slug")
        ]
    summaries: list[dict] = []
    missing: list[str] = []
    for project_id, slug in targets:
        root = project_root(conn, project_id)
        if root is None:
            missing.append(slug)
            continue
        found, skipped = walk(root, [*DEFAULT_ROOTS, *item_dirs(conn, project_id)])
        with _write(conn):
            added, changed, removed = _store(conn, project_id, found, stamp)
        summaries.append({
            "project": slug, "root": str(root), "items": len(found),
            "added": added, "changed": changed, "removed": removed, "skipped": skipped,
        })
    return {"projects": summaries, "missing": missing}


def project_item_names(conn: sqlite3.Connection) -> list[str]:
    """Distinct names of every scanned project item, sorted."""
    return [row["name"] for row in conn.execute("SELECT DISTINCT name FROM project_items ORDER BY name")]
