DEFAULT_ROOTS = (
    ".agents/skills",
    ".claude/skills",
    ".opencode/skills",
    ".cursor/skills",
    "agents",
    ".claude/agents",
    ".opencode/agents",
    ".agents/agents",
    ".cursor/agents",
)
AGENT_FILE_ROOTS = (".claude/agents", ".opencode/agents", ".cursor/agents")
AGY_AGENTS_ROOT = ".agents/agents"
MAX_DEPTH = 4
SKIPPED_NAMES = ("node_modules",)
GENERATED_PREFIX = "# generated by chanchi"
BLOCK_MARKER = re.compile(r"^[>|][+-]?\d*$")
_FIELDS = ("kind", "name", "sha256", "lines", "description")


@contextmanager
def _write(conn: sqlite3.Connection) -> Iterator[sqlite3.Connection]:
    """One write transaction; joins the caller's transaction when one is already open."""
    if conn.in_transaction:
        yield conn
    else:
        with db.transaction(conn):
            yield conn


# --- project root and item dirs -----------------------------------------------------------


def project_root(conn: sqlite3.Connection, project_id: int) -> Path | None:
    """The first path locator of the project (lowest id) that is an existing directory, else None."""
    for row in conn.execute(
        "SELECT value FROM project_locators WHERE project_id = ? AND kind = 'path' ORDER BY id",
        (project_id,),
    ):
        candidate = Path(row["value"])
        if candidate.is_dir():
            return candidate
    return None


def require_root(conn: sqlite3.Connection, project_id: int, slug: str) -> Path:
    root = project_root(conn, project_id)
    if root is None:
        raise ChanchiError(
            "missing_prerequisite",
            f"project {slug!r} has no existing folder on this machine",
            field="project",
            hint=f"cd into the project and run `chanchi project relink {slug}`",
        )
    return root


def _bad_path(message: str, *, hint: str | None = None) -> ChanchiError:
    return ChanchiError("invalid_value", message, field="path", hint=hint)


def _normalize(path: str) -> str:
    """A relative POSIX path without empty or `.` components; refuses anything that could leave the root."""
    if not isinstance(path, str) or not path.strip():
        raise _bad_path("path must not be empty", hint="pass a folder relative to the project root")
    if "\0" in path:
        raise _bad_path("path must not contain a NUL character")
    if path.startswith("/"):
        raise _bad_path(f"{path!r} is absolute", hint="pass a path relative to the project root")
    parts = [part for part in path.split("/") if part not in ("", ".")]
    if ".." in parts:
        raise _bad_path(f"{path!r} contains '..'", hint="pass a path inside the project root")
    if not parts:
        raise _bad_path(f"{path!r} is the project root itself", hint="pass a folder below the project root")
    return "/".join(parts)


def _root_state(root: Path, rel: str) -> str:
    """`ok` when every component from the project root down to `rel` is a real directory,
    `symlink` when one is a link (never entered), `absent` when one is missing or not a directory."""
    current = root
    for part in rel.split("/"):
        current = current / part
        try:
            mode = os.lstat(current).st_mode
        except OSError:
            return "absent"
        if stat.S_ISLNK(mode):
            return "symlink"
        if not stat.S_ISDIR(mode):
            return "absent"
    return "ok"


def item_dirs(conn: sqlite3.Connection, project_id: int) -> list[str]:
    """The agnostic folders the project registered with `project items-dirs --add`, sorted."""
    rows = conn.execute("SELECT path FROM project_item_dirs WHERE project_id = ? ORDER BY path", (project_id,))
    return [row["path"] for row in rows]


def add_item_dir(conn: sqlite3.Connection, project_id: int, root: Path, path: str) -> dict:
    """Register an extra scan root: an existing real directory below `root`, not a default root."""
    norm = _normalize(path)
    if norm in DEFAULT_ROOTS:
        raise _bad_path(f"{norm} is already scanned by default", hint="pass another folder")
    state = _root_state(Path(root), norm)
    if state == "symlink":
        raise _bad_path(f"{norm} is or sits under a symbolic link; scans never follow links")
    if state == "absent":
        raise _bad_path(f"{norm} is not an existing directory under the project root")
    with _write(conn):
        stored = conn.execute(
            "SELECT 1 FROM project_item_dirs WHERE project_id = ? AND path = ?", (project_id, norm)
        ).fetchone()
        if stored is not None:
            return {"path": norm, "added": False}
        conn.execute("INSERT INTO project_item_dirs (project_id, path) VALUES (?, ?)", (project_id, norm))
    return {"path": norm, "added": True}


def remove_item_dir(conn: sqlite3.Connection, project_id: int, path: str) -> dict:
    """Delete a registered scan root; a path that is not registered is refused."""
    norm = _normalize(path)
    with _write(conn):
        cursor = conn.execute("DELETE FROM project_item_dirs WHERE project_id = ? AND path = ?", (project_id, norm))
        if cursor.rowcount == 0:
            raise _bad_path(
                f"{norm} is not a registered item folder",
                hint="run `chanchi project items-dirs` to list them",
            )
    return {"path": norm, "removed": True}


# --- frontmatter ----------------------------------------------------------------------------


def _block(text: str) -> list[str] | None:
    """The lines between a first-line `---` fence and the next `---` line, or None."""
    lines = text.lstrip("﻿").split("\n")
    if not lines or lines[0].rstrip() != "---":
        return None
    for index in range(1, len(lines)):
        if lines[index].rstrip() == "---":
            return [line.rstrip("\r") for line in lines[1:index]]
    return None


def _unquote(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def frontmatter(text: str) -> dict:
    """A lenient reader for `name` and `description`; it never raises.

    Comment lines are ignored; a description that is empty or a `>`, `>-`, `|` or `|-` marker takes the
    more-indented lines that follow, joined with single spaces. The strict `items.read_frontmatter`
    refuses folded values, comments and nested maps that project files use.
    """
    found: dict[str, str | None] = {"name": None, "description": None}
    block = _block(text)
    if block is None:
        return found
    seen: set[str] = set()
    index = 0
    while index < len(block):
        line = block[index]
        index += 1
        if not line.strip() or line[0] in " \t" or line.startswith("#"):
            continue
        key, sep, value = line.partition(":")
        key, value = key.strip(), value.strip()
        if not sep or key not in found or key in seen:
            continue
        seen.add(key)
        if not value or BLOCK_MARKER.match(value):
            parts = []
            while index < len(block) and (block[index][:1] in (" ", "\t") or not block[index].strip()):
                if block[index].strip():
                    parts.append(block[index].strip())
                index += 1
            value = " ".join(parts)
        else:
            value = _unquote(value).strip()
        found[key] = value or None
    return found


def description(text: str) -> str | None:
    return frontmatter(text)["description"]


def _generated(text: str) -> bool:
    block = _block(text)
    return block is not None and any(line.startswith(GENERATED_PREFIX) for line in block)


# --- walk -----------------------------------------------------------------------------------


class _Walk:
    def __init__(self, root: Path) -> None:
        self.root = root
        self.found: dict[str, dict] = {}
        self.skipped: set[tuple[str, str]] = set()

    def skip(self, path: str, reason: str) -> None:
        self.skipped.add((path, reason))

    def directory(self, rel: str, depth: int) -> None:
        folder = self.root / rel
        try:
            with os.scandir(folder) as scanned:
                entries = sorted(scanned, key=lambda e: e.name)
        except OSError:
            self.skip(rel, "unreadable")
            return
        main = self._main_file(entries, rel)
        if main is not None:
            self.item(rel, *main)
            return
        for entry in entries:
            name = entry.name
            if name.startswith(".") or name in SKIPPED_NAMES:
                continue
            child = f"{rel}/{name}"
            if entry.is_symlink():
                self.skip(child, "symlink")
            elif entry.is_dir(follow_symlinks=False):
                if depth < MAX_DEPTH:
                    self.directory(child, depth + 1)
            elif rel in AGENT_FILE_ROOTS and name.endswith(".md") and entry.is_file(follow_symlinks=False):
                self.single_file(child, name)

    @staticmethod
    def _main_file(entries: list[os.DirEntry], rel: str) -> tuple[str, str, bool] | None:
        """(kind, main file name, main file is a link) when the directory is an item."""
        by_name = {entry.name: entry for entry in entries}
        wanted = [("skill", "SKILL.md"), ("agent", "AGENT.md")]
        if posixpath.dirname(rel) == AGY_AGENTS_ROOT:
            wanted.append(("agent", "agent.md"))
        for kind, name in wanted:
            entry = by_name.get(name)
            if entry is None:
                continue
            if entry.is_symlink():
                return kind, name, True
            if entry.is_file(follow_symlinks=False):
                return kind, name, False
        return None

    def item(self, rel: str, kind: str, main_name: str, linked: bool) -> None:
        if linked:
            self.skip(rel, "symlink")
            return
        folder = self.root / rel
        try:
            text = (folder / main_name).read_bytes().decode("utf-8")
        except (OSError, UnicodeDecodeError):
            self.skip(rel, "unreadable")
            return
        if _generated(text):
            self.skip(rel, "generated")
            return
        try:
            digest = items.content_hash(folder)
        except ChanchiError:
            self.skip(rel, "symlink")
            return
        except OSError:
            self.skip(rel, "unreadable")
            return
        meta = frontmatter(text)
        self.found[rel] = {
            "kind": kind,
            "name": meta["name"] or folder.name,
            "path": rel,
            "sha256": digest,
            "lines": len(text.splitlines()),
            "description": meta["description"],
        }

    def single_file(self, rel: str, file_name: str) -> None:
        try:
            data = (self.root / rel).read_bytes()
            text = data.decode("utf-8")
        except (OSError, UnicodeDecodeError):
            self.skip(rel, "unreadable")
            return
        if _generated(text):
            self.skip(rel, "generated")
            return
        meta = frontmatter(text)
        self.found[rel] = {
            "kind": "agent",
            "name": meta["name"] or file_name[: -len(".md")],
            "path": rel,
            "sha256": hashlib.sha256(data).hexdigest(),
            "lines": len(text.splitlines()),
            "description": meta["description"],
        }


def walk(root: Path, rel_roots: list[str]) -> tuple[list[dict], list[dict]]:
    """Items `{kind, name, path, sha256, lines, description}` and skipped `{path, reason}` below `root`.

    Each root in `rel_roots` is walked only when it and every component above it are real directories
    (checked with `lstat`); a linked one is listed as skipped and never entered. Reads files, never
    writes and never follows a link.
    """
    state = _Walk(Path(root))
    for rel in rel_roots:
        status = _root_state(state.root, rel)
        if status == "symlink":
            state.skip(rel, "symlink")
        elif status == "ok":
            state.directory(rel, 0)
    found = [state.found[path] for path in sorted(state.found)]
    skipped = [{"path": path, "reason": reason} for path, reason in sorted(state.skipped)]
    return found, skipped


# --- scan -----------------------------------------------------------------------------------


def _store(conn: sqlite3.Connection, project_id: int, found: list[dict], stamp: str) -> tuple[int, int, int]:
    """Insert new paths, update changed rows, delete vanished ones; stamp every row seen."""
    existing = {
        row["path"]: row
        for row in conn.execute("SELECT * FROM project_items WHERE project_id = ?", (project_id,))
    }
    added = changed = 0
    for item in found:
        row = existing.pop(item["path"], None)
        if row is None:
            conn.execute(
                "INSERT INTO project_items (project_id, kind, name, path, sha256, lines, description, scanned_at) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                (project_id, item["kind"], item["name"], item["path"], item["sha256"], item["lines"],
                 item["description"], stamp),
            )
            added += 1
        elif all(row[field] == item[field] for field in _FIELDS):
            conn.execute("UPDATE project_items SET scanned_at = ? WHERE id = ?", (stamp, row["id"]))
        else:
            conn.execute(
                "UPDATE project_items SET kind = ?, name = ?, sha256 = ?, lines = ?, description = ?, "
                "scanned_at = ? WHERE id = ?",
                (item["kind"], item["name"], item["sha256"], item["lines"], item["description"], stamp, row["id"]),
            )
            changed += 1
    for row in existing.values():
        conn.execute("DELETE FROM project_items WHERE id = ?", (row["id"],))
    return added, changed, len(existing)


def scan(conn: sqlite3.Connection, *, project: str | None = None, now: str | None = None) -> dict:
    """Fingerprint the items of every registered project (or one) into `project_items`.

    A project whose root is missing is listed under `missing` and keeps its stored rows. Each project is
    written in one transaction; a second scan of unchanged projects adds, changes and removes nothing.
    """
    stamp = now or utc_now()
    if project is not None:
        described = projects.show(conn, project)
        targets = [(described["id"], described["slug"])]
    else:
        targets = [
            (row["id"], row["slug"])
            for row in conn.execute("SELECT id, slug FROM projects WHERE registered_at IS NOT NULL ORDER BY slug")
        ]
    summaries: list[dict] = []
    missing: list[str] = []
    for project_id, slug in targets:
        root = project_root(conn, project_id)
        if root is None:
            missing.append(slug)
            continue
        found, skipped = walk(root, [*DEFAULT_ROOTS, *item_dirs(conn, project_id)])
        with _write(conn):
            added, changed, removed = _store(conn, project_id, found, stamp)
        summaries.append({
            "project": slug, "root": str(root), "items": len(found),
            "added": added, "changed": changed, "removed": removed, "skipped": skipped,
        })
    return {"projects": summaries, "missing": missing}


def project_item_names(conn: sqlite3.Connection) -> list[str]:
    """Distinct names of every scanned project item, sorted."""
    return [row["name"] for row in conn.execute("SELECT DISTINCT name FROM project_items ORDER BY name")]


# --- propose --------------------------------------------------------------------------------

LESSON_TARGET = re.compile(r"^(skill|role|agent)\s+([a-z0-9][a-z0-9._-]*)(\s+\(new\))?$", re.IGNORECASE)
LESSON_KIND = {"skill": "skill", "role": "agent", "agent": "agent"}
RULE_ORDER = ("same_name", "description_overlap", "lessons")
TOKEN = re.compile(r"[a-z0-9]+")
MIN_TOKENS = 5
MIN_TOKEN_LENGTH = 4
MIN_JACCARD = 0.5
PROPOSAL_FIELDS = ("id", "kind", "name", "status", "uses", "owner_promoted", "eligible", "global_item",
                   "created_at", "updated_at", "evidence")


def slug_of(name: str) -> str:
    """The name lowercased, every run of characters outside `[a-z0-9]` replaced by `-`, `-` stripped."""
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def _chanchi_name(name: str, slug: str, own: set[str]) -> bool:
    """Chanchi's own items, global items and items of the `<item>-chanchi-<project>-<name>` form."""
    if name in own or slug in own:
        return True
    for form in (name.lower(), slug):
        if "-chanchi-global-" in form or form.startswith(("skill-chanchi-", "agent-chanchi-")):
            return True
    return False


def longest_shared_block(a: list[str], b: list[str]) -> tuple[int, int, int]:
    """`(a_start, b_start, size)`, 0-based starts, of the longest run of identical consecutive lines."""
    match = difflib.SequenceMatcher(None, a, b, autojunk=False).find_longest_match(0, len(a), 0, len(b))
    return match.a, match.b, match.size


def _tokens(text: str | None) -> frozenset[str]:
    return frozenset(t for t in TOKEN.findall((text or "").lower()) if len(t) >= MIN_TOKEN_LENGTH)


def _jaccard(a: frozenset[str], b: frozenset[str]) -> float:
    return len(a & b) / len(a | b)


class _Groups:
    """Union-find over hashable keys."""

    def __init__(self) -> None:
        self.parent: dict = {}

    def find(self, key):
        self.parent.setdefault(key, key)
        while self.parent[key] != key:
            self.parent[key] = self.parent[self.parent[key]]
            key = self.parent[key]
        return key

    def union(self, a, b) -> None:
        self.parent[self.find(a)] = self.find(b)

    def groups(self, keys) -> list[list]:
        found: dict = {}
        for key in keys:
            found.setdefault(self.find(key), []).append(key)
        return list(found.values())


def _copy_key(copy: dict) -> str:
    return f"{copy['project']}:{copy['path']}"


def _copy_order(row) -> tuple:
    """Canonical copy first: most lines, then shortest path, then alphabetical."""
    return (-row["lines"], len(row["path"]), row["path"])


def _inventory(conn: sqlite3.Connection, own: set[str]) -> tuple[dict, list[str], list[dict]]:
    """Canonical copies by `(kind, slug)` and project, the projects with no root, and the names with no slug.

    Chanchi's own names, global names and project-own `<item>-chanchi-...` names are left out first.
    """
    canonical: dict[tuple[str, str], dict[str, dict]] = {}
    missing: list[str] = []
    skipped: list[dict] = []
    for project in conn.execute("SELECT id, slug FROM projects WHERE registered_at IS NOT NULL ORDER BY slug"):
        if project_root(conn, project["id"]) is None:
            missing.append(project["slug"])
            continue
        rows = conn.execute(
            "SELECT * FROM project_items WHERE project_id = ? AND kind IN ('skill', 'agent') ORDER BY path",
            (project["id"],),
        ).fetchall()
        grouped: dict[tuple[str, str], list] = {}
        for row in rows:
            slug = slug_of(row["name"])
            if _chanchi_name(row["name"], slug, own):
                continue
            if not slug:
                skipped.append({"project": project["slug"], "kind": row["kind"], "name": row["name"]})
                continue
            grouped.setdefault((row["kind"], slug), []).append(row)
        for key, copies in grouped.items():
            copies.sort(key=_copy_order)
            first = copies[0]
            canonical.setdefault(key, {})[project["slug"]] = {
                "project": project["slug"], "project_id": project["id"], "kind": first["kind"],
                "name": first["name"], "path": first["path"], "sha256": first["sha256"],
                "lines": first["lines"], "description": first["description"],
                "aliases": sorted(row["path"] for row in copies[1:]),
            }
    return canonical, missing, sorted(skipped, key=lambda s: (s["project"], s["kind"], s["name"]))


def _lesson_groups(conn: sqlite3.Connection, own: set[str]) -> dict[tuple[str, str], list[dict]]:
    """Agnostic lessons that name one item, grouped by `(kind, slug)`; at least two distinct projects."""
    rows = conn.execute(
        "SELECT l.id, l.target, l.status, l.origin_project_id, p.slug AS project FROM lessons l "
        "JOIN projects p ON p.id = l.origin_project_id "
        "WHERE l.generality = 'agnostic' AND l.target_kind IN ('skill', 'role') "
        "AND l.status IN ('pending', 'approved') ORDER BY l.id"
    ).fetchall()
    groups: dict[tuple[str, str], list[dict]] = {}
    for row in rows:
        match = LESSON_TARGET.match(row["target"].strip())
        if match is None:
            continue
        name = match.group(2)
        slug = slug_of(name)
        if not slug or _chanchi_name(name, slug, own):
            continue
        groups.setdefault((LESSON_KIND[match.group(1).lower()], slug), []).append(
            {"id": row["id"], "project": row["project"], "status": row["status"], "project_id": row["origin_project_id"]}
        )
    return {key: found for key, found in groups.items() if len({x["project_id"] for x in found}) >= 2}


def _candidates(conn: sqlite3.Connection, own: set[str]) -> tuple[dict, list[str], list[dict]]:
    """`{(kind, slug): {kind, slug, rules, copies, lessons}}` plus the projects with no root and skipped names."""
    canonical, missing, skipped = _inventory(conn, own)
    found: dict[tuple[str, str], dict] = {}

    def add(kind: str, slug: str, rule: str, copies: list[dict], lessons: list[dict] = ()) -> None:
        entry = found.setdefault((kind, slug), {"kind": kind, "slug": slug, "rules": [], "copies": [], "lessons": []})
        entry["rules"].append(rule)
        entry["copies"] += copies
        entry["lessons"] += list(lessons)

    for (kind, slug), by_project in sorted(canonical.items()):
        if len(by_project) >= 2:
            add(kind, slug, "same_name", [by_project[p] for p in sorted(by_project)])
    pool = [
        copy for (kind, slug), by_project in sorted(canonical.items()) if (kind, slug) not in found
        for copy in by_project.values()
    ]
    pool.sort(key=lambda c: (c["kind"], c["project"], c["path"]))
    groups = _Groups()
    for index, left in enumerate(pool):
        left_tokens = _tokens(left["description"])
        if len(left_tokens) < MIN_TOKENS:
            continue
        for right in pool[index + 1:]:
            right_tokens = _tokens(right["description"])
            if (right["kind"] == left["kind"] and right["project"] != left["project"]
                    and len(right_tokens) >= MIN_TOKENS and _jaccard(left_tokens, right_tokens) >= MIN_JACCARD):
                groups.union(_copy_key(left), _copy_key(right))
    by_key = {_copy_key(copy): copy for copy in pool}
    for members in groups.groups([k for k in by_key if k in groups.parent]):
        copies = sorted((by_key[k] for k in members), key=lambda c: (c["project"], c["path"]))
        if len({c["project"] for c in copies}) < 2:
            continue
        longest = min(copies, key=lambda c: (-c["lines"], slug_of(c["name"]), c["project"], c["path"]))
        add(longest["kind"], slug_of(longest["name"]), "description_overlap", copies)
    for (kind, slug), lessons in sorted(_lesson_groups(conn, own).items()):
        add(kind, slug, "lessons", [], lessons)
    for entry in found.values():
        entry["rules"].sort(key=RULE_ORDER.index)
    return found, missing, skipped


def _fresh(root: Path, copy: dict) -> tuple[str, list[str]] | str:
    """`(sha256, main file lines)` of the item stored at `copy["path"]`, or the reason it is stale.

    Reads without following any link along the path: `missing`, `symlink`, `unreadable` or `changed`.
    """
    current = root
    mode = stat.S_IFDIR
    for part in copy["path"].split("/"):
        current = current / part
        try:
            mode = os.lstat(current).st_mode
        except OSError:
            return "missing"
        if stat.S_ISLNK(mode):
            return "symlink"
    try:
        if stat.S_ISDIR(mode):
            with os.scandir(current) as scanned:
                entries = sorted(scanned, key=lambda e: e.name)
            main = _Walk._main_file(entries, copy["path"])
            if main is None:
                return "missing"
            _, main_name, linked = main
            if linked:
                return "symlink"
            text = (current / main_name).read_bytes().decode("utf-8")
            try:
                digest = items.content_hash(current)
            except ChanchiError:
                return "symlink"
        elif stat.S_ISREG(mode):
            data = current.read_bytes()
            text = data.decode("utf-8")
            digest = hashlib.sha256(data).hexdigest()
        else:
            return "missing"
    except (OSError, UnicodeDecodeError):
        return "unreadable"
    return (digest, text.splitlines()) if digest == copy["sha256"] else "changed"


def _check_fresh(conn: sqlite3.Connection, candidates: dict) -> dict[str, list[str]]:
    """Lines of every counted copy, or `missing_prerequisite` listing every stale one."""
    roots: dict[int, Path | None] = {}
    lines: dict[str, list[str]] = {}
    stale: list[dict] = []
    copies = {_copy_key(c): c for entry in candidates.values() for c in entry["copies"]}
    for key in sorted(copies):
        copy = copies[key]
        root = roots.setdefault(copy["project_id"], project_root(conn, copy["project_id"]))
        result = "missing" if root is None else _fresh(root, copy)
        if isinstance(result, str):
            stale.append({"project": copy["project"], "path": copy["path"], "reason": result})
        else:
            lines[key] = result[1]
    if stale:
        raise ChanchiError(
            "missing_prerequisite",
            f"{len(stale)} counted copy(ies) changed since the last scan",
            field="items",
            hint="chanchi items scan",
            details={"stale": sorted(stale, key=lambda s: (s["project"], s["path"]))},
        )
    return lines


def _evidence(entry: dict, lines: dict[str, list[str]], config: dict) -> tuple[dict, int]:
    """The stored evidence of one candidate and its independent uses."""
    copies = sorted(entry["copies"], key=lambda c: (c["project"], c["path"]))
    groups = _Groups()
    pairs = []
    for index, left in enumerate(copies):
        groups.find(_copy_key(left))
        for right in copies[index + 1:]:
            a, b = lines[_copy_key(left)], lines[_copy_key(right)]
            a_start, b_start, size = longest_shared_block(a, b)
            share = size / min(len(a), len(b)) if a and b else 0.0
            pairs.append({"a": _copy_key(left), "b": _copy_key(right), "block_lines": size,
                          "a_start": a_start + 1, "b_start": b_start + 1, "share": share})
            if share >= config["vendored_share"]:
                groups.union(_copy_key(left), _copy_key(right))
    clusters = sorted(sorted(group) for group in groups.groups([_copy_key(c) for c in copies]))
    lessons = [{"id": x["id"], "project": x["project"], "status": x["status"]} for x in entry["lessons"]]
    uses = len(clusters) + sum(1 for x in lessons if x["status"] == "approved")
    evidence = {
        "rules": entry["rules"],
        "copies": [
            {"project": c["project"], "kind": c["kind"], "name": c["name"], "path": c["path"],
             "sha256": c["sha256"], "lines": c["lines"], "aliases": c["aliases"]}
            for c in copies
        ],
        "pairs": pairs,
        "clusters": clusters,
        "lessons": lessons,
        "min_uses": config["min_uses"],
        "vendored_share": config["vendored_share"],
    }
    return evidence, uses


def _printed(row: sqlite3.Row, config: dict) -> dict:
    return {
        "id": row["id"], "kind": row["kind"], "name": row["name"], "status": row["status"], "uses": row["uses"],
        "owner_promoted": bool(row["owner_promoted"]),
        "eligible": bool(row["owner_promoted"]) or row["uses"] >= config["min_uses"],
        "global_item": row["global_item"], "created_at": row["created_at"], "updated_at": row["updated_at"],
        "evidence": json.loads(row["evidence"]),
    }


def _proposal_name(kind: str, slug: str) -> str:
    return f"{kind}-chanchi-global-{slug}"


def propose(
    conn: sqlite3.Connection, *, own_names, config: dict, owner_promote: str | None = None, now: str | None = None
) -> dict:
    """Detect candidates from the scanned items and the lessons, count independent uses and store them.

    Three rules: the same name in two projects, overlapping descriptions, agnostic lessons naming one item.
    Copies of a project with no folder on this machine are left out (`missing`); any other copy that changed
    since the scan fails the run with `missing_prerequisite` and nothing is stored. An open proposal keeps
    its id across runs and its `owner_promoted` flag; a built or rejected one is listed under `closed`.
    """
    stamp = now or utc_now()
    candidates, missing, skipped = _candidates(conn, set(own_names))
    lines = _check_fresh(conn, candidates)
    produced = {_proposal_name(kind, slug): entry for (kind, slug), entry in candidates.items()}
    plan: list[tuple[str, dict, sqlite3.Row | None]] = []
    closed: list[dict] = []
    for name in sorted(produced):
        entry = produced[name]
        row = conn.execute(
            "SELECT * FROM item_proposals WHERE kind = ? AND name = ? ORDER BY (status = 'open') DESC, id DESC",
            (entry["kind"], name),
        ).fetchone()
        if row is not None and row["status"] != "open":
            closed.append({"id": row["id"], "kind": row["kind"], "name": row["name"],
                           "status": row["status"], "global_item": row["global_item"]})
        else:
            plan.append((name, entry, row))
    if owner_promote is not None and owner_promote not in {name for name, _, _ in plan}:
        if owner_promote in {c["name"] for c in closed}:
            raise ChanchiError(
                "invalid_value",
                f"{owner_promote!r} is already built or rejected and cannot be promoted",
                field="owner_promote",
                hint="`chanchi items proposals` lists every proposal with its status",
            )
        raise ChanchiError(
            "invalid_value",
            f"this run produces no candidate named {owner_promote!r}",
            field="owner_promote",
            valid_values=[name for name, _, _ in plan],
            hint="run `chanchi items scan`, then `chanchi items propose` to list the candidates",
        )
    stored: list[int] = []
    with _write(conn):
        for name, entry, row in plan:
            evidence, uses = _evidence(entry, lines, config)
            payload = json.dumps(evidence, ensure_ascii=False)
            promoted = 1 if name == owner_promote else 0
            if row is None:
                cursor = conn.execute(
                    "INSERT INTO item_proposals (kind, name, evidence, uses, owner_promoted, status, "
                    "created_at, updated_at) VALUES (?, ?, ?, ?, ?, 'open', ?, ?)",
                    (entry["kind"], name, payload, uses, promoted, stamp, stamp),
                )
                stored.append(cursor.lastrowid)
            else:
                conn.execute(
                    "UPDATE item_proposals SET evidence = ?, uses = ?, owner_promoted = MAX(owner_promoted, ?), "
                    "updated_at = ? WHERE id = ?",
                    (payload, uses, promoted, stamp, row["id"]),
                )
                stored.append(row["id"])
        not_found = [
            {"id": row["id"], "kind": row["kind"], "name": row["name"]}
            for row in conn.execute("SELECT * FROM item_proposals WHERE status = 'open' ORDER BY id")
            if row["id"] not in stored
        ]
        printed = [
            _printed(conn.execute("SELECT * FROM item_proposals WHERE id = ?", (proposal_id,)).fetchone(), config)
            for proposal_id in stored
        ]
    return {
        "proposals": printed,
        "closed": closed,
        "not_found": not_found,
        "missing": missing,
        "skipped_names": skipped,
        "min_uses": config["min_uses"],
        "vendored_share": config["vendored_share"],
    }


