def _write_source(root: Path, name: str, *, install: str | None = None, scope: str = "both", profile: str = "read-only") -> None:
    src = root / "agents" / name
    src.mkdir(parents=True, exist_ok=True)
    extra = f"install: {install}\n" if install is not None else ""
    (src / "AGENT.md").write_text(
        f"---\nname: {name}\ndescription: Test agent {name}.\nscope: {scope}\nprofile: {profile}\n{extra}skills: []\n---\n\nBody for {name}.\n",
        encoding="utf-8",
    )


def _setup_two_sources(tmp_path: Path, *, repo_name: str = "repo") -> tuple[Path, Path, Path]:
    root = tmp_path / repo_name
    _write_source(root, "agent-chanchi-user", install="user")
    _write_source(root, "agent-chanchi-repo")
    home = tmp_path / "home"
    (home / ".claude").mkdir(parents=True)
    (home / ".config" / "opencode").mkdir(parents=True)
    (home / ".gemini").mkdir(parents=True)
    db_dir = tmp_path / "db"
    return root, home, db_dir


