def test_link_user_writes_only_user_install_and_records_manifest(tmp_path):
    root, home, db_dir = _setup_two_sources(tmp_path)
    res = agents_sync.link_user(root, env={}, home=home, db_dir=db_dir)
    claude = home / ".claude" / "agents" / "agent-chanchi-user.md"
    opencode = home / ".config" / "opencode" / "agents" / "agent-chanchi-user.md"
    agy = home / ".gemini" / "config" / "agents" / "agent-chanchi-user" / "agent.md"
    assert sorted(res["written"]) == sorted([str(claude), str(opencode), str(agy)])
    assert res["unchanged"] == []
    assert res["removed"] == []
    assert res["conflicts"] == []
    assert res["skipped_harnesses"] == []
    header = "# generated by chanchi agents link --user from agents/agent-chanchi-user/AGENT.md; do not edit"
    for path in (claude, opencode, agy):
        assert path.is_file()
        assert header in path.read_text(encoding="utf-8")
    assert not (home / ".claude" / "agents" / "agent-chanchi-repo.md").exists()

    import json
    manifest = json.loads((db_dir / "mirror.json").read_text(encoding="utf-8"))
    assert manifest["version"] == 1
    assert len(manifest["entries"]) == 3
    for entry in manifest["entries"]:
        assert entry["owner"] == "agents-link"
        assert entry["root"] == str(root.resolve())
        assert entry["kind"] in ("claude", "opencode", "agy")
        assert len(entry["sha256"]) == 64

    # Idempotent second run
    again = agents_sync.link_user(root, env={}, home=home, db_dir=db_dir)
    assert again["written"] == []
    assert sorted(again["unchanged"]) == sorted([str(claude), str(opencode), str(agy)])


