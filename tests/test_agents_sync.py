from pathlib import Path

import pytest

from chanchi import agents_sync, cli
from chanchi.errors import ChanchiError

ROOT = Path(__file__).resolve().parents[1]

SOURCE = """---
name: agent-chanchi-demo
description: Demo agent for tests.
scope: {scope}
profile: {profile}
skills: [skill-chanchi-verify]
---

# Demo

Do the demo work.
"""


def make_repo(tmp_path, scope="both", profile="workspace-write"):
    src = tmp_path / "agents" / "agent-chanchi-demo"
    src.mkdir(parents=True)
    (src / "AGENT.md").write_text(SOURCE.format(scope=scope, profile=profile))
    return tmp_path


def test_render_paths(tmp_path):
    (source,) = agents_sync.load_sources(make_repo(tmp_path) / "agents")
    assert sorted(agents_sync.render(source)) == [
        ".agents/agents/agent-chanchi-demo/agent.md",
        ".claude/agents/agent-chanchi-demo.md",
        ".opencode/agents/agent-chanchi-demo.md",
    ]


def test_claude_subagent_scope_inlines_body_and_preloads(tmp_path):
    (source,) = agents_sync.load_sources(make_repo(tmp_path, scope="both") / "agents")
    text = agents_sync.render(source)[".claude/agents/agent-chanchi-demo.md"]
    head, body = text.split("\n---\n", 1)
    assert "name: agent-chanchi-demo" in head
    assert "skills:\n  - skill-chanchi-verify" in head
    assert "# generated by chanchi agents sync from agents/agent-chanchi-demo/AGENT.md; do not edit" in head
    assert "Do the demo work." in body
    assert "initialPrompt" not in head


def test_claude_main_scope_keeps_body_empty(tmp_path):
    (source,) = agents_sync.load_sources(make_repo(tmp_path, scope="main") / "agents")
    text = agents_sync.render(source)[".claude/agents/agent-chanchi-demo.md"]
    head, body = text.split("\n---\n", 1)
    assert body.strip() == ""
    assert "initialPrompt: |" in head
    assert "Do the demo work." in head
    assert "Before starting, load these skills: skill-chanchi-verify." in head


def test_opencode_mode_permission_and_skill_line(tmp_path):
    (source,) = agents_sync.load_sources(make_repo(tmp_path, scope="subagent", profile="read-only") / "agents")
    text = agents_sync.render(source)[".opencode/agents/agent-chanchi-demo.md"]
    assert "mode: subagent" in text
    assert "permission:\n  edit: deny\n  write: deny" in text
    assert "Before starting, load these skills: skill-chanchi-verify." in text


def test_agy_flags_and_tools(tmp_path):
    (source,) = agents_sync.load_sources(make_repo(tmp_path, scope="subagent", profile="read-only") / "agents")
    text = agents_sync.render(source)[".agents/agents/agent-chanchi-demo/agent.md"]
    assert "mainAgent: false" in text and "subagent: true" in text
    assert "  - view_file" in text and "replace_file_content" not in text


def test_sync_then_check_is_clean(tmp_path):
    root = make_repo(tmp_path)
    first = agents_sync.sync(root)
    assert len(first["written"]) == 3
    assert agents_sync.sync(root, check=True)["unchanged"] == sorted(first["written"])


def test_check_detects_hand_edit(tmp_path):
    root = make_repo(tmp_path)
    agents_sync.sync(root)
    wrapper = root / ".claude" / "agents" / "agent-chanchi-demo.md"
    wrapper.write_text(wrapper.read_text() + "\nhand edit\n")
    with pytest.raises(ChanchiError) as info:
        agents_sync.sync(root, check=True)
    assert info.value.code == "stale_wrappers"
    assert ".claude/agents/agent-chanchi-demo.md" in info.value.details["stale"]


def test_orphan_wrapper_is_removed(tmp_path):
    root = make_repo(tmp_path)
    agents_sync.sync(root)
    orphan = root / ".opencode" / "agents" / "agent-chanchi-gone.md"
    orphan.write_text("old")
    with pytest.raises(ChanchiError):
        agents_sync.sync(root, check=True)
    assert ".opencode/agents/agent-chanchi-gone.md" in agents_sync.sync(root)["removed"]


@pytest.mark.parametrize("field,value", [("scope", "sometimes"), ("profile", "root")])
def test_invalid_source_is_refused(tmp_path, field, value):
    kwargs = {"scope": "both", "profile": "read-only", field: value}
    root = make_repo(tmp_path, **kwargs)
    with pytest.raises(ChanchiError) as info:
        agents_sync.load_sources(root / "agents")
    assert info.value.field == field


def test_claude_wrappers_frontmatter():
    """Design verification plan 3: every committed Claude wrapper has the fields Claude reads."""
    for path in sorted((ROOT / ".claude" / "agents").glob("agent-chanchi-*.md")):
        head, body = path.read_text().split("\n---\n", 1)
        assert head.startswith("---\n"), path
        assert f"name: {path.stem}" in head and "description: " in head, path
        if "initialPrompt: |" in head:
            assert body.strip() == "", f"{path}: a main-scope wrapper keeps its body empty"
        else:
            assert body.strip(), f"{path}: a subagent wrapper carries the role in its body"


def test_repository_wrappers_are_in_sync():
    """Check 2: committed wrappers equal what the generator writes."""
    agents_sync.sync(ROOT, check=True)


def test_cli_check(capsys):
    assert cli.main(["agents", "sync", str(ROOT), "--check"]) == 0
    capsys.readouterr()
