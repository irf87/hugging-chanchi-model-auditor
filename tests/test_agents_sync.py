def test_link_user_check_and_repair(tmp_path):
    root, home, db_dir = _setup_two_sources(tmp_path)
    # Before first link: --check fails without creating db_dir or mirror.json
    with pytest.raises(ChanchiError) as info:
        agents_sync.link_user(root, env={}, home=home, db_dir=db_dir, check=True)
    assert info.value.code == "stale_wrappers"
    assert not (db_dir / "mirror.json").exists()

    agents_sync.link_user(root, env={}, home=home, db_dir=db_dir)
    assert agents_sync.link_user(root, env={}, home=home, db_dir=db_dir, check=True)["written"] == []

    # Hand edit is detected by --check and repaired by normal run
    target = home / ".claude" / "agents" / "agent-chanchi-user.md"
    target.write_text("hand edit\n", encoding="utf-8")
    with pytest.raises(ChanchiError) as info:
        agents_sync.link_user(root, env={}, home=home, db_dir=db_dir, check=True)
    assert info.value.code == "stale_wrappers"
    assert str(target) in target.read_text(encoding="utf-8") or target.read_text(encoding="utf-8") == "hand edit\n"

    repaired = agents_sync.link_user(root, env={}, home=home, db_dir=db_dir)
    assert repaired["written"] == [str(target)]
    assert "hand edit" not in target.read_text(encoding="utf-8")


def test_link_user_conflict_writes_nothing(tmp_path):
    root, home, db_dir = _setup_two_sources(tmp_path)
    foreign = home / ".claude" / "agents" / "agent-chanchi-user.md"
    foreign.parent.mkdir(parents=True, exist_ok=True)
    foreign.write_text("foreign user agent\n", encoding="utf-8")

    with pytest.raises(ChanchiError) as info:
        agents_sync.link_user(root, env={}, home=home, db_dir=db_dir)
    assert info.value.code == "link_conflict"
    assert str(foreign) in info.value.details["conflicts"]
    assert foreign.read_text(encoding="utf-8") == "foreign user agent\n"
    assert not (home / ".config" / "opencode" / "agents" / "agent-chanchi-user.md").exists()
    assert not (home / ".gemini" / "config" / "agents" / "agent-chanchi-user" / "agent.md").exists()
    assert not (db_dir / "mirror.json").exists()

    with pytest.raises(ChanchiError) as check_info:
        agents_sync.link_user(root, env={}, home=home, db_dir=db_dir, check=True)
    assert check_info.value.code == "stale_wrappers"


def test_link_user_preserves_other_owners_and_roots_and_removes_cleanly(tmp_path):
    import json
    root_a, home, db_dir = _setup_two_sources(tmp_path, repo_name="repo-a")
    root_b = tmp_path / "repo-b"
    _write_source(root_b, "agent-chanchi-other", install="user")

    db_dir.mkdir(parents=True, exist_ok=True)
    items_mirror_entry = {
        "owner": "items-mirror",
        "path": str(home / ".claude" / "agents" / "agent-chanchi-global-x.md"),
        "kind": "agent",
        "sha256": "abc",
        "custom": {"keep": True},
    }
    (db_dir / "mirror.json").write_text(json.dumps({"version": 1, "entries": [items_mirror_entry]}), encoding="utf-8")

    agents_sync.link_user(root_a, env={}, home=home, db_dir=db_dir)
    agents_sync.link_user(root_b, env={}, home=home, db_dir=db_dir)

    # Change root_a's source back to repo: orphan is removed by link_user
    _write_source(root_a, "agent-chanchi-user", install="repo")
    with pytest.raises(ChanchiError) as info:
        agents_sync.link_user(root_a, env={}, home=home, db_dir=db_dir, check=True)
    assert info.value.code == "stale_wrappers"
    res = agents_sync.link_user(root_a, env={}, home=home, db_dir=db_dir)
    assert len(res["removed"]) == 3
    assert not (home / ".gemini" / "config" / "agents" / "agent-chanchi-user").exists()
    # root_b and items-mirror survive
    assert (home / ".claude" / "agents" / "agent-chanchi-other.md").is_file()

    # Re-link root_a, then --remove root_a
    _write_source(root_a, "agent-chanchi-user", install="user")
    agents_sync.link_user(root_a, env={}, home=home, db_dir=db_dir)
    rem = agents_sync.link_user(root_a, env={}, home=home, db_dir=db_dir, remove=True)
    assert len(rem["removed"]) == 3
    assert not (home / ".claude" / "agents" / "agent-chanchi-user.md").exists()
    assert not (home / ".config" / "opencode" / "agents" / "agent-chanchi-user.md").exists()
    assert not (home / ".gemini" / "config" / "agents" / "agent-chanchi-user").exists()
    # root_b and items-mirror entry still intact
    assert (home / ".claude" / "agents" / "agent-chanchi-other.md").is_file()
    manifest = json.loads((db_dir / "mirror.json").read_text(encoding="utf-8"))
    assert items_mirror_entry in manifest["entries"]
    assert any(e["owner"] == "agents-link" and e["root"] == str(root_b.resolve()) for e in manifest["entries"])
    assert not any(e.get("root") == str(root_a.resolve()) for e in manifest["entries"])


def test_link_user_check_and_remove_exclusive_and_cli(tmp_path, monkeypatch, capsys):
    import json
    root, home, db_dir = _setup_two_sources(tmp_path)
    with pytest.raises(ChanchiError) as info:
        agents_sync.link_user(root, env={}, home=home, db_dir=db_dir, check=True, remove=True)
    assert info.value.code == "invalid_value"

    # --remove without existing mirror.json does not create db_dir
    agents_sync.link_user(root, env={}, home=home, db_dir=db_dir, remove=True)
    assert not db_dir.exists()

    monkeypatch.setenv("HOME", str(home))
    monkeypatch.setenv("CHANCHI_DB", str(db_dir / "chanchi.db"))
    monkeypatch.delenv("OPENCODE_CONFIG_DIR", raising=False)
    monkeypatch.delenv("XDG_CONFIG_HOME", raising=False)

    assert cli.main(["agents", "link", str(root)]) == 2
    err = json.loads(capsys.readouterr().err)
    assert err["error"]["code"] == "invalid_value"
    assert err["error"]["hint"] == "chanchi agents link --user"

    assert cli.main(["agents", "link", "--user", str(root)]) == 0
    capsys.readouterr()
    assert cli.main(["agents", "link", "--user", "--check", str(root)]) == 0
    capsys.readouterr()
    assert cli.main(["agents", "link", "--user", "--remove", str(root)]) == 0
    capsys.readouterr()
    assert not (home / ".claude" / "agents" / "agent-chanchi-user.md").exists()


def test_link_user_worktree_normalization_and_cli_default_root(tmp_path, monkeypatch, capsys):
    import json
    import subprocess
    repo = tmp_path / "git-repo"
    repo.mkdir()
    subprocess.run(["git", "init", "-q"], cwd=repo, check=True)
    subprocess.run(["git", "config", "user.email", "test@example.com"], cwd=repo, check=True)
    subprocess.run(["git", "config", "user.name", "Test"], cwd=repo, check=True)
    _write_source(repo, "agent-chanchi-wt", install="user")
    subprocess.run(["git", "add", "."], cwd=repo, check=True)
    subprocess.run(["git", "commit", "-q", "-m", "init"], cwd=repo, check=True)
    wt = tmp_path / "wt"
    subprocess.run(["git", "worktree", "add", "-q", str(wt)], cwd=repo, check=True)

    home = tmp_path / "home"
    (home / ".claude").mkdir(parents=True)
    db_dir = tmp_path / "db"

    res = agents_sync.link_user(wt, env={}, home=home, db_dir=db_dir)
    assert res["root"] == str(repo.resolve())
    assert agents_sync.link_user(repo, env={}, home=home, db_dir=db_dir, check=True)["written"] == []
    rem = agents_sync.link_user(repo, env={}, home=home, db_dir=db_dir, remove=True)
    assert len(rem["removed"]) == 1

    # Missing owned file detected by --check
    agents_sync.link_user(repo, env={}, home=home, db_dir=db_dir)
    (home / ".claude" / "agents" / "agent-chanchi-wt.md").unlink()
    with pytest.raises(ChanchiError) as info:
        agents_sync.link_user(repo, env={}, home=home, db_dir=db_dir, check=True)
    assert info.value.code == "stale_wrappers"

    # CLI without <root> uses chanchi's repository, never cwd
    monkeypatch.setenv("HOME", str(home))
    monkeypatch.setenv("CHANCHI_DB", str(tmp_path / "db2" / "chanchi.db"))
    monkeypatch.delenv("OPENCODE_CONFIG_DIR", raising=False)
    monkeypatch.delenv("XDG_CONFIG_HOME", raising=False)
    monkeypatch.chdir(repo)
    assert cli.main(["agents", "link", "--user"]) == 0
    out = json.loads(capsys.readouterr().out)
    assert "agent-chanchi-wt" not in out["agents"]
    assert out["root"] == str(agents_sync._normalize_root(ROOT))


def test_optional_version_and_status_are_parsed_and_never_rendered(tmp_path):
    repo = make_repo(tmp_path)
    path = repo / "agents" / "agent-chanchi-demo" / "AGENT.md"
    (plain,) = agents_sync.load_sources(repo / "agents")
    assert (plain.version, plain.status) == (None, None)
    path.write_text(path.read_text().replace("skills:", 'version: "1.2.3"\nstatus: published\nskills:', 1))
    (versioned,) = agents_sync.load_sources(repo / "agents")
    assert (versioned.version, versioned.status) == ("1.2.3", "published")
    assert agents_sync.render(versioned) == agents_sync.render(plain)
    assert "1.2.3" not in "".join(agents_sync.render(versioned).values())


