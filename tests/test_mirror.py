SKILL_PUB = "skill-chanchi-global-pub"
SKILL_DRAFT = "skill-chanchi-global-draft"
AGENT_PUB = "agent-chanchi-global-pub"
AGENT_DRAFT = "agent-chanchi-global-draft"
HEADER = "# generated by chanchi items mirror from SYNC/ITEMS/agents/{name}/AGENT.md; do not edit"

SKILL = """---
name: {name}
description: Demo skill.
metadata:
  version: "0.1.0"
  status: "{status}"
---

# Demo

Answer exactly the probe token.
"""

AGENT = """---
name: {name}
description: Demo agent.
scope: both
profile: read-only
skills: [skill-chanchi-global-pub]
version: 0.1.0
status: {status}
---

# Demo

State your agent name.
"""

CHANGELOG = "# Changelog\n\n## 0.1.0 — 2026-11-22\n\n- First draft.\n"


def write_item(sync_root: Path, kind: str, name: str, *, published: bool) -> Path:
    folder = "skills" if kind == "skill" else "agents"
    item = sync_root / "ITEMS" / folder / name
    item.mkdir(parents=True)
    template = SKILL if kind == "skill" else AGENT
    manifest = "SKILL.md" if kind == "skill" else "AGENT.md"
    (item / manifest).write_text(template.format(name=name, status="published" if published else "draft"))
    changelog = CHANGELOG
    if published:
        digest = items.content_hash(item)
        changelog += f"\nPublished: 2026-11-23 · audit 1 · audited {digest} · sha256 {digest}\n"
    (item / "CHANGELOG.md").write_text(changelog)
    return item


@dataclass
class World:
    home: Path
    db: Path
    sync: Path
    env: dict

    def run(self, **kw):
        return items.mirror(self.sync, env=self.env, home=self.home, db_dir=self.db, own_names=[], **kw)

    def manifest(self) -> list[dict]:
        return json.loads((self.db / "mirror.json").read_text())["entries"]

    def skill_paths(self, name: str, *, agy=True) -> list[Path]:
        paths = [self.home / ".agents" / "skills" / name, self.home / ".claude" / "skills" / name]
        if agy:
            paths.append(self.home / ".gemini" / "antigravity-cli" / "skills" / name)
        return paths

    def agent_paths(self, name: str, *, opencode=True, cursor=True) -> list[Path]:
        paths = [self.home / ".claude" / "agents" / f"{name}.md",
                 self.home / ".gemini" / "config" / "agents" / name / "agent.md"]
        if opencode:
            paths.append(self.home / ".config" / "opencode" / "agents" / f"{name}.md")
        if cursor:
            paths.append(self.home / ".cursor" / "agents" / f"{name}.md")
        return paths

    def leftovers(self) -> list[str]:
        return sorted(str(p) for p in self.home.rglob("*") if "chanchi-global-" in p.name)


@pytest.fixture
def world(tmp_path):
    home = tmp_path / "home"
    for folder in (".claude", ".config/opencode", ".gemini/antigravity-cli", ".cursor"):
        (home / folder).mkdir(parents=True)
    root = tmp_path / "SYNC"
    for kind, pub, draft in (("skill", SKILL_PUB, SKILL_DRAFT), ("agent", AGENT_PUB, AGENT_DRAFT)):
        write_item(root, kind, pub, published=True)
        write_item(root, kind, draft, published=False)
    return World(home=home, db=tmp_path / "db", sync=root, env={})


def strs(paths) -> list[str]:
    return sorted(str(p) for p in paths)


def test_mirror_writes_skill_links_and_agent_files_for_published_items_only(world):
    result = world.run()
    skills = world.skill_paths(SKILL_PUB)
    agents = world.agent_paths(AGENT_PUB)
    assert result["written"] == strs(skills + agents)
    assert result["unchanged"] == [] and result["removed"] == [] and result["conflicts"] == []
    assert result["skipped_harnesses"] == []
    assert result["items"] == sorted([SKILL_PUB, AGENT_PUB])

    primary, claude, agy = skills
    assert os.readlink(primary) == str(world.sync / "ITEMS" / "skills" / SKILL_PUB)
    assert os.readlink(claude) == os.path.join("..", "..", ".agents", "skills", SKILL_PUB)
    assert os.readlink(agy) == os.path.join("..", "..", "..", ".agents", "skills", SKILL_PUB)
    assert (claude / "SKILL.md").is_file() and (agy / "SKILL.md").is_file()
    for path in agents:
        text = path.read_text()
        assert HEADER.format(name=AGENT_PUB) in text
        assert f"{AGENT_PUB}" in text and "agents link --user" not in text
    named = [p for p in agents if p.name != "agent.md"] + [p.parent for p in agents if p.name == "agent.md"]
    assert world.leftovers() == strs([*skills, *named])
    assert not [p for p in world.home.rglob("*") if "draft" in p.name]

    entries = world.manifest()
    assert {e["kind"] for e in entries} == {"skill-primary", "skill-secondary", "claude", "opencode", "agy", "cursor"}
    for entry in entries:
        assert entry["owner"] == "items-mirror" and "root" not in entry
        assert entry["item"] in (SKILL_PUB, AGENT_PUB)
        assert ("sha256" in entry) != ("link" in entry)


