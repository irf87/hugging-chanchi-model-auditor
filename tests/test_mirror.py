def agents_link_entry(world, path: Path) -> dict:
    return {"owner": "agents-link", "root": "/somewhere/else", "path": str(path), "kind": "claude",
            "sha256": "ab" * 32}


def test_agents_link_entries_survive_mirror_and_remove_byte_for_byte(world):
    own_agent = world.home / ".claude" / "agents" / "agent-chanchi-own.md"
    own_agent.parent.mkdir(parents=True)
    own_agent.write_text("agents link file\n")
    entry = agents_link_entry(world, own_agent)
    world.db.mkdir()
    (world.db / "mirror.json").write_text(json.dumps({"version": 1, "entries": [entry]}, indent=2) + "\n")

    world.run()
    assert entry in world.manifest() and world.manifest()[0] == entry
    world.run()
    world.run(remove=True)
    assert world.manifest() == [entry]
    assert json.dumps(world.manifest()[0]) == json.dumps(entry)
    assert own_agent.read_text() == "agents link file\n"
    assert world.leftovers() == []


def test_a_path_owned_by_agents_link_is_a_conflict_for_the_mirror_and_the_reverse(world, tmp_path):
    claimed = world.home / ".claude" / "agents" / f"{AGENT_PUB}.md"
    claimed.parent.mkdir(parents=True)
    claimed.write_text("agents link file\n")
    world.db.mkdir()
    (world.db / "mirror.json").write_text(
        json.dumps({"version": 1, "entries": [agents_link_entry(world, claimed)]}) + "\n")
    with pytest.raises(ChanchiError) as info:
        world.run()
    assert info.value.code == "link_conflict" and str(claimed) in info.value.details["conflicts"]
    assert claimed.read_text() == "agents link file\n"

    # the reverse: a path the mirror owns is a conflict for `agents link --user`
    other = tmp_path / "other-home"
    (other / ".claude").mkdir(parents=True)
    mirrored = World(home=other, db=tmp_path / "db2", sync=world.sync, env={})
    mirrored.run()
    repo = tmp_path / "repo"
    source = repo / "agents" / AGENT_PUB
    source.mkdir(parents=True)
    (source / "AGENT.md").write_text(
        f"---\nname: {AGENT_PUB}\ndescription: x\nscope: both\nprofile: read-only\ninstall: user\nskills: []\n---\n\nx\n")
    with pytest.raises(ChanchiError) as reverse:
        agents_sync.link_user(repo, env={}, home=other, db_dir=mirrored.db)
    assert reverse.value.code == "link_conflict"


def test_skill_links_use_the_unresolved_sync_path_and_survive_repointing(tmp_path, world):
    env = {"CHANCHI_SYNC": str(tmp_path / "LINKED")}
    cloud_a, cloud_b = tmp_path / "cloud-a", tmp_path / "cloud-b"
    sync.init(env, link=cloud_a)
    linked = tmp_path / "LINKED"
    assert linked.is_symlink()
    write_item(linked, "skill", SKILL_PUB, published=True)
    write_item(linked, "agent", AGENT_PUB, published=True)
    linked_world = World(home=world.home, db=world.db, sync=linked, env={})

    first = linked_world.run()
    primary = world.home / ".agents" / "skills" / SKILL_PUB
    assert os.readlink(primary) == f"{linked}/ITEMS/skills/{SKILL_PUB}"
    assert str(cloud_a) not in os.readlink(primary)

    shutil.copytree(cloud_a, cloud_b)
    linked.unlink()
    linked.symlink_to(cloud_b)
    shutil.rmtree(cloud_a)
    second = linked_world.run()
    assert second["written"] == [] and second["removed"] == []
    assert second["unchanged"] == first["written"]
    assert (primary / "SKILL.md").is_file()
    assert linked_world.run(check=True)["written"] == []


