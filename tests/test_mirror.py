def own_skills(tmp_path) -> Path:
    root = tmp_path / "repo" / "skills"
    for name in ("skill-chanchi-a", "skill-chanchi-b"):
        (root / name).mkdir(parents=True)
        (root / name / "SKILL.md").write_text(f"---\nname: {name}\ndescription: x\n---\n")
    return root


def test_skills_unlink_leaves_every_mirror_entry_and_mirror_remove_leaves_every_own_link(tmp_path, world):
    own = own_skills(tmp_path)
    skills_link.link(world.home, global_=True, skills_dir=own)
    world.run()
    applied = world.leftovers()

    primary, claude, agy = world.skill_paths(SKILL_PUB)
    primary.unlink()  # the secondaries now dangle
    legacy_shaped = world.home / ".claude" / "skills" / "chanchi-global-x"
    legacy_shaped.symlink_to(os.path.join("..", "..", ".agents", "skills", "chanchi-global-x"))

    removed = skills_link.unlink(world.home, global_=True, skills_dir=own)["removed"]
    assert all("global" not in Path(path).name for path in removed) and len(removed) == 10
    assert claude.is_symlink() and agy.is_symlink() and legacy_shaped.is_symlink()
    assert [p for p in applied if not os.path.lexists(p) and p != str(primary)] == []
    for agent in world.agent_paths(AGENT_PUB):
        assert agent.is_file()

    skills_link.link(world.home, global_=True, skills_dir=own)
    primary.symlink_to(world.sync / "ITEMS" / "skills" / SKILL_PUB)
    result = world.run(remove=True)
    assert world.leftovers() == [str(legacy_shaped)] and str(legacy_shaped) not in result["removed"]
    for directory in (world.home / ".agents" / "skills", world.home / ".claude" / "skills",
                      world.home / ".gemini" / "antigravity-cli" / "skills"):
        names = sorted(p.name for p in directory.iterdir() if "global" not in p.name)
        assert names == (["skill-chanchi-a", "skill-chanchi-b"] if "gemini" in str(directory) else
                         ["chanchi-a", "chanchi-b", "skill-chanchi-a", "skill-chanchi-b"])


